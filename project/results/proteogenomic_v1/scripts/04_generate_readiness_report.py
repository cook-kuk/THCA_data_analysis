#!/usr/bin/env python3
"""Step 4 — generate human-readable integration readiness report.

Reads everything in --processed-dir produced by steps 01–03 and writes:
  - integration_readiness_report.md   (sample/modality summary, missingness)
  - next_analysis_plan.md             (downstream candidate analyses)

Clinical claims here are framed as exploratory only.
"""
from __future__ import annotations
import argparse
import sys
from pathlib import Path
import pandas as pd


def block(title: str, body: str) -> str:
    return f"## {title}\n\n{body}\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--processed-dir", required=True, type=Path)
    args = ap.parse_args()
    pd_dir = args.processed_dir
    if not pd_dir.exists():
        sys.exit(f"ERROR: --processed-dir not found: {pd_dir}")

    # ---- Read what's there ----
    sample_path = pd_dir / "harmonized_thyroid_multiomics_sample_index.tsv"
    feature_path = pd_dir / "harmonized_thyroid_multiomics_feature_index.tsv"
    inv_path = pd_dir / "raw_file_manifest.tsv"
    crm_inv = pd_dir / "cellrepmed2026_sheet_inventory.tsv"
    mtbls_qc = pd_dir / "mtbls3339_qc_report.md"
    crm_qc = pd_dir / "cellrepmed2026_qc_report.md"

    samp = pd.read_csv(sample_path, sep="\t", dtype=str) if sample_path.exists() else pd.DataFrame()
    feat = pd.read_csv(feature_path, sep="\t", dtype=str) if feature_path.exists() else pd.DataFrame()

    sections = ["# Thyroid multi-omics integration readiness",
                "*Generated by `scripts/04_generate_readiness_report.py` "
                "— treat clinical claims as exploratory.*", ""]

    # ---- Cohort summary ----
    if not samp.empty:
        by_cohort = (samp.groupby("cohort")
                     .agg(n_rows=("sample_id", "size"),
                          n_unique_sample=("sample_id", lambda s: s.nunique()),
                          n_unique_patient=("patient_id", lambda s: s.nunique()))
                     .reset_index())
        sections.append(block("Per-cohort sample counts",
                              by_cohort.to_markdown(index=False)))

        # subtype distribution
        sub_table = (samp[samp["subtype"].astype(str).str.len() > 0]
                     .groupby(["cohort", "subtype"]).size()
                     .rename("n").reset_index())
        if not sub_table.empty:
            sections.append(block("Subtype/cluster distribution",
                                  sub_table.to_markdown(index=False)))
        else:
            sections.append(block("Subtype/cluster distribution",
                                  "No subtype calls detected in either cohort."))

        # recurrence risk distribution
        rr = (samp[samp["recurrence_risk"].astype(str).str.len() > 0]
              .groupby(["cohort", "recurrence_risk"]).size()
              .rename("n").reset_index())
        if not rr.empty:
            sections.append(block("Recurrence-risk distribution (MTBLS3339 expected)",
                                  rr.to_markdown(index=False)))
        else:
            sections.append(block("Recurrence-risk distribution",
                                  "No `recurrence_risk` values populated yet."))

        # mapping confidence
        mc = samp.groupby(["cohort", "mapping_confidence"]).size().rename("n").reset_index()
        sections.append(block("Sample-ID mapping confidence",
                              mc.to_markdown(index=False)))
    else:
        sections.append(block("Per-cohort sample counts",
                              "**Sample index is empty** — re-run steps 01–03 after raw "
                              "data is in place. The MTBLS3339 / cellrepmed2026 raw "
                              "directories may still hold HTML SPA pages instead of real "
                              "ISA-Tab / xlsx files (see `raw_file_manifest.tsv` "
                              "`html_failed_dl` flags)."))

    # ---- Feature summary ----
    if not feat.empty:
        feat_count = (feat.groupby(["cohort", "feature_type"]).size()
                      .rename("n_features").reset_index())
        sections.append(block("Feature counts", feat_count.to_markdown(index=False)))
    else:
        sections.append(block("Feature counts",
                              "Feature index empty — abundance matrices not yet ingested."))

    # ---- Modality matrix ----
    sections.append(block("Modality presence (per cohort)",
                          "MTBLS3339: metabolomics (untargeted MS/MS or NMR per ISA-Tab).\n"
                          "CellRepMed2026: proteomic + (likely) clinical/subtype calls + "
                          "external scRNA/spatial validation cohorts referenced.\n\n"
                          "**Boundary reminder:** HLA / arcasHLA work is on a separate "
                          "validation track (`v17_arcasHLA_korean_k2`) and is intentionally "
                          "NOT joined into this index."))

    # ---- Missingness ----
    if not samp.empty:
        miss = (samp[["disease_stage", "histology", "recurrence_risk", "subtype",
                       "patient_id"]]
                .applymap(lambda x: 1 if str(x).strip() == "" else 0).mean()
                .mul(100).round(1).rename("pct_missing").to_frame())
        sections.append(block("Field-level missingness (% empty across all rows)",
                              miss.to_markdown()))

    # ---- QC pointers ----
    pointers = []
    if inv_path.exists():
        pointers.append(f"- raw inventory: `{inv_path.name}`")
    if mtbls_qc.exists():
        pointers.append(f"- MTBLS QC: `{mtbls_qc.name}`")
    if crm_qc.exists():
        pointers.append(f"- CRM QC: `{crm_qc.name}`")
    if crm_inv.exists():
        pointers.append(f"- CRM sheet inventory: `{crm_inv.name}`")
    sections.append(block("Pointers", "\n".join(pointers) or "(none)"))

    out_path = pd_dir / "integration_readiness_report.md"
    out_path.write_text("\n".join(sections) + "\n")
    print(f"[04] readiness → {out_path}")

    # ---- Next-analysis plan ----
    plan = ["# Next analysis plan — proteogenomic_v1\n",
            "*Marathon-mode rules apply: any of these that count as new sprint analysis "
            "must wait for explicit user greenlight.*\n",
            "## 1. Recurrence-risk metabolic subtype replication (MTBLS3339)",
            "- Use harmonized sample index → metabolite long matrix.",
            "- Test thyroid-hormone pathway metabolites (T3/T4/MIT/DIT/iodotyrosine + "
            "tyrosine, iodide proxies if measured) for recurrence-risk-stratified diff.",
            "- Cross-reference with Wang 2024 RNA panel and our 8-gene panel: do the "
            "metabolites correlate with the same dediff axis?",
            "- Output: `metabolomics_recurrence_risk_diff.tsv` + a `metabolite_x_8gene_corr.tsv`.\n",
            "## 2. Advanced DTC CC1/CC2/CC3 proteomic characterization (CellRepMed2026)",
            "- Map our DIAL-lite 7-module gene list onto the protein matrix.",
            "- Compute module mean per sample, group by CC1/CC2/CC3.",
            "- Compare CC3 (immunogenic) module profile to Mun 2025 ATC profile from "
            "`paper3_mun2025_dediff_layer/module_ATC_vs_PTC.tsv`. If CC3 ≈ ATC, the "
            "advanced-DTC immunogenic phenotype is on the same dediff axis we already "
            "characterized — strong replication evidence for Paper 3 reviewer-reserve.\n",
            "## 3. Immune / metabolic / lineage axis comparison",
            "- Combine #1 + #2: metabolomic phenotype (MTBLS) ↔ proteomic phenotype (CRM).",
            "- Boundary: same direction at the *cohort-level summary*, NOT sample-level merge.",
            "- This is the cleanest reviewer-reserve framing: 'three independent cohorts "
            "(Wang RNA+protein, Mun protein+phospho, CRM advanced DTC protein, MTBLS "
            "metabolomics) point to the same dediff axis.'\n",
            "## 4. External public-data validation hooks",
            "- TCGA-THCA HM450 methylation (n=503): already on disk, integrated into "
            "Paper 1 reviewer-reserve memo.",
            "- TCGA-THCA miRNA-seq from GDC: deferred (sprint-class).",
            "- Lu 2023 ATC scRNA per-cell-type 7-module: deferred (sprint-class).\n",
            "## Boundary reminders",
            "- HLA validation stays on a separate track (`v17_arcasHLA_korean_k2`).",
            "- Track B (Paper 3) remains FROZEN until Paper 1 bioRxiv + Paper 2 A/B/C + "
            "explicit unfreeze (`v19_paper3_ici_track_a`).",
            "- Voice-protected manuscript sections (Hook/Aim/Disc 3.1/Limitations/Cover Para 1/Q9) "
            "are author-keyboard only.",
            ]
    plan_path = pd_dir / "next_analysis_plan.md"
    plan_path.write_text("\n".join(plan) + "\n")
    print(f"[04] plan → {plan_path}")


if __name__ == "__main__":
    main()
